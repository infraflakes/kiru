//! Generate the embedded standard library table from `std/**`.
//!
//! The library is a directory tree, so the table that compiles it into the
//! binary is a product of that tree rather than a second declaration beside it.
//! The build walks `std/` for every `.kiru` file and writes one `include_str!`
//! entry per file; adding a library file therefore cannot be forgotten.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets the manifest directory"),
    );
    let root = manifest.join("std");
    println!("cargo:rerun-if-changed=std");

    let mut files = Vec::new();
    collect(&root, &root, &mut files);
    files.sort();

    let mut generated = String::from("// Generated by build.rs from `std/**`; do not edit.\n\n");
    generated.push_str("/// The standard library's files, one per `.kiru` file under `std/`.\n");
    generated.push_str("/// Each file's directory under `std/` is its namespace.\n");
    generated.push_str("pub(crate) const EMBEDDED: &[(&str, &str)] = &[\n");
    for file in &files {
        let absolute = root.join(file);
        let relative = file.to_string_lossy().replace('\\', "/");
        writeln!(
            generated,
            "    (\"{relative}\", include_str!({:?})),",
            absolute.to_string_lossy()
        )
        .expect("writing to a string cannot fail");
    }
    generated.push_str("];\n");

    let output = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets the output directory"))
        .join("embedded_library.rs");
    std::fs::write(output, generated).expect("writing the generated library table");
}

/// Every `.kiru` file under `directory`, as a path relative to `root`.
fn collect(root: &Path, directory: &Path, out: &mut Vec<PathBuf>) {
    let entries = std::fs::read_dir(directory).expect("the standard library directory is readable");
    for entry in entries {
        let entry = entry.expect("a standard library directory entry is readable");
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path
            .extension()
            .is_some_and(|extension| extension == "kiru")
        {
            out.push(
                path.strip_prefix(root)
                    .expect("a library file is under the library root")
                    .to_path_buf(),
            );
        }
    }
}
